"""Scenario execution: (candidate, Scenario) -> the loop's game record.

Produces exactly the mapping shape :class:`optimizer.loop.OptimizerLoop`
expects from its injected ``run_scenario`` callable:

    score           section-11 game score for the candidate's side
    new_exceptions  candidate robots threw (DieAction EXCEPTION) this game
    cache_hit       exact-cache hit (exempt from the match budget)

plus passthrough fields the trace decoder and analysis use: ``replay_path``,
``opponent``, ``map_name``, ``side``, ``outcome``, ``margin``, ``win_type``,
``winner``, ``total_rounds``, ``exception_count``.

Matches are cached in the shared exact :class:`harness.MatchCache` keyed by
(engine commit, seat-A bot hash, seat-B bot hash, map, candidate side, runner
config); cached entries store outcome/margin raw so the score can always be
recomputed under the current margin lambda.
"""

from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path
from typing import Any, Mapping, Optional, Union

from evaluation.scoring import (
    DEFAULT_MARGIN_LAMBDA,
    game_outcome,
    game_score,
    is_backstabbed,
    points_margin,
    stats_from_footer,
)
from harness.cache import MatchCache, MatchCacheKey, source_tree_hash
from harness.runner import EngineConfig
from opponents.lockfile import OpponentEntry, load_lockfile
from optimizer.candidate import Candidate
from optimizer.feedback_sampler import Scenario
from replay import decode_match
from replay.decoder import TEAM_STAT_KEYS

from .candidates import CandidateCompiler, CompiledCandidate

__all__ = ["ScenarioError", "load_opponents", "ScenarioExecutor", "runner_config_hash"]

_REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OPPONENTS_LOCK = _REPO_ROOT / "configs" / "opponents.lock.json"

# Fixed headless flags every match runs under (same base string as
# scripts/calibrate_opponents.py so the convention stays uniform).
_RUNNER_CONFIG = b"headless;validateMaps=false;alternateOrder=false;showIndicators=false"


def runner_config_hash() -> str:
    return hashlib.sha256(_RUNNER_CONFIG).hexdigest()


class ScenarioError(RuntimeError):
    """A scenario cannot be run (missing lockfile, unusable opponent, ...)."""


def load_opponents(
    lock_path: Union[str, Path] = DEFAULT_OPPONENTS_LOCK,
) -> dict[str, OpponentEntry]:
    """Load configs/opponents.lock.json as an id -> entry mapping.

    Raises :class:`ScenarioError` with a clear message if the lockfile does
    not exist yet (it is generated by scripts/build_opponents.py).
    """
    lock_path = Path(lock_path)
    if not lock_path.exists():
        raise ScenarioError(
            f"opponents lockfile missing: {lock_path} -- run "
            "scripts/build_opponents.py first (PLAN.md section 10)"
        )
    return {e.id: e for e in load_lockfile(lock_path)}


def _robot_teams(decoded: Mapping[str, Any]) -> dict[int, str]:
    """robot id -> team letter, from initial bodies plus every SpawnAction."""
    teams: dict[int, str] = {}
    for b in decoded["header"]["initial_bodies"]:
        teams[b["id"]] = b["team"]
    for rnd in decoded["rounds"]:
        for turn in rnd["turns"]:
            for a in turn["actions"]:
                if a["type"] == "SpawnAction":
                    teams[a["spawn_id"]] = a["team"]
    return teams


def exception_count_for_side(decoded: Mapping[str, Any], side: str) -> int:
    """Number of DieAction EXCEPTION deaths among ``side``'s robots."""
    teams = _robot_teams(decoded)
    count = 0
    for rnd in decoded["rounds"]:
        for turn in rnd["turns"]:
            for a in turn["actions"]:
                if a["type"] == "DieAction" and a.get("die_type") == "EXCEPTION":
                    if teams.get(a["target_id"]) == side:
                        count += 1
    return count


def backstab_flag(decoded: Mapping[str, Any]) -> bool:
    """True if any turn recorded the cooperation -> backstab flip."""
    for rnd in decoded["rounds"]:
        for turn in rnd["turns"]:
            if turn["team"] in ("A", "B") and not turn["is_cooperation"]:
                return True
    return False


class ScenarioExecutor:
    """Runs (candidate, scenario) cells through the runner + exact cache."""

    def __init__(
        self,
        cache: MatchCache,
        runner: Any,  # DirectRunner or anything with the same run_match surface
        opponents: Mapping[str, OpponentEntry],
        compiler: CandidateCompiler,
        engine: Optional[EngineConfig] = None,
        replay_dir: Union[str, Path, None] = None,
        margin_lambda: float = DEFAULT_MARGIN_LAMBDA,
        match_timeout_s: int = 2700,
    ):
        self.cache = cache
        self.runner = runner
        self.opponents = dict(opponents)
        self.compiler = compiler
        self.engine = engine if engine is not None else EngineConfig.from_lock()
        # Keep replay paths SHORT: the gradle fallback truncates paths >100
        # chars (engine build.gradle mangling handled by harness, but short
        # paths avoid the temp-relay entirely).
        self.replay_dir = Path(replay_dir) if replay_dir is not None else Path("/tmp/gepa_replays")
        self.replay_dir.mkdir(parents=True, exist_ok=True)
        self.margin_lambda = float(margin_lambda)
        self.match_timeout_s = match_timeout_s
        self.config_hash = runner_config_hash()
        self._opponent_hashes: dict[str, str] = {}

    # ------------------------------------------------------------------

    def _opponent(self, opponent_id: str) -> OpponentEntry:
        entry = self.opponents.get(opponent_id)
        if entry is None:
            raise ScenarioError(
                f"unknown opponent {opponent_id!r}; known: {sorted(self.opponents)}"
            )
        if not entry.compiled or not entry.smoke_ok:
            raise ScenarioError(
                f"opponent {opponent_id!r} is not usable "
                f"(compiled={entry.compiled}, smoke_ok={entry.smoke_ok})"
            )
        if entry.source_dir is not None and entry.classes_dir is None:
            raise ScenarioError(
                f"opponent {opponent_id!r} has sources but no classes_dir; "
                "rerun scripts/build_opponents.py"
            )
        return entry

    def _opponent_hash(self, entry: OpponentEntry) -> str:
        cached = self._opponent_hashes.get(entry.id)
        if cached is not None:
            return cached
        if entry.source_dir is None:
            h = f"builtin:{entry.package}@{entry.commit}"
        else:
            h = source_tree_hash(Path(entry.source_dir) / entry.package)
        self._opponent_hashes[entry.id] = h
        return h

    def _key(
        self, compiled: CompiledCandidate, opp_hash: str, scenario: Scenario
    ) -> MatchCacheKey:
        side = scenario.side.upper()
        if side not in ("A", "B"):
            raise ScenarioError(f"scenario side must be 'A' or 'B', got {scenario.side!r}")
        cand_hash = f"candidate:{compiled.candidate_id}"
        bot_a, bot_b = (
            (cand_hash, opp_hash) if side == "A" else (opp_hash, cand_hash)
        )
        return MatchCacheKey(
            engine_commit=self.engine.commit,
            bot_a_hash=bot_a,
            bot_b_hash=bot_b,
            map_name=scenario.map_name,
            side=side,
            config_hash=self.config_hash,
        )

    # ------------------------------------------------------------------

    def run_scenario(
        self,
        candidate: Union[Candidate, CompiledCandidate],
        scenario: Scenario,
    ) -> dict[str, Any]:
        """The OptimizerLoop ``run_scenario`` injected callable."""
        if isinstance(candidate, CompiledCandidate):
            compiled = candidate
        else:
            compiled = self.compiler.compiled_for(candidate)

        opp = self._opponent(scenario.opponent)
        key = self._key(compiled, self._opponent_hash(opp), scenario)
        side = scenario.side.upper()

        hit = self.cache.get(key)
        if hit is not None:
            record = dict(hit)
            record["cache_hit"] = True
            record["score"] = game_score(
                float(record["outcome"]), float(record["margin"]), self.margin_lambda
            )
            return record

        # Per-process temp name: concurrent runs (paired CRN schedules) play the
        # same match key at the same time, and a shared deterministic filename
        # races (one process consumes the replay another just wrote).
        replay_out = self.replay_dir / f"{key.digest()[:16]}_{os.getpid()}.bc26"
        if side == "A":
            result = self.runner.run_match(
                team_a=compiled.package,
                team_b=opp.package,
                map_name=scenario.map_name,
                replay_out=replay_out,
                class_location_a=compiled.classes_dir,
                class_location_b=opp.classes_dir,
                timeout_s=self.match_timeout_s,
            )
        else:
            result = self.runner.run_match(
                team_a=opp.package,
                team_b=compiled.package,
                map_name=scenario.map_name,
                replay_out=replay_out,
                class_location_a=opp.classes_dir,
                class_location_b=compiled.classes_dir,
                timeout_s=self.match_timeout_s,
            )

        decoded = decode_match(result.replay_path)
        footer = decoded["footer"]
        if decoded["rounds"]:
            final_stats = decoded["rounds"][-1]["team_stats"]
        else:
            zeros = {k: 0 for k in TEAM_STAT_KEYS}
            final_stats = {"A": dict(zeros), "B": dict(zeros)}
        stats = stats_from_footer({"final_team_stats": final_stats})
        outcome = game_outcome(footer["win_type"], footer["winner"], side)
        backstabbed = is_backstabbed(footer["win_type"], backstab_flag(decoded))
        margin = points_margin(stats, backstabbed, side)
        exc_count = exception_count_for_side(decoded, side)

        record: dict[str, Any] = {
            "opponent": scenario.opponent,
            "map_name": scenario.map_name,
            "side": side,
            "candidate_id": compiled.candidate_id,
            "outcome": outcome,
            "margin": margin,
            "backstabbed": backstabbed,
            "win_type": footer["win_type"],
            "winner": footer["winner"],
            "total_rounds": footer["total_rounds"],
            "exception_count": exc_count,
            "new_exceptions": exc_count > 0,
            "duration_s": result.duration_s,
        }
        stored = self.cache.put(key, record, result.replay_path)
        # Authoritative replay copy now lives in the cache; drop the working copy.
        replay_out.unlink(missing_ok=True)

        out = dict(stored)
        out["cache_hit"] = False
        out["score"] = game_score(outcome, margin, self.margin_lambda)
        return out
